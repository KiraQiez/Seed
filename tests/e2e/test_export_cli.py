"""Round-trip the actual export command through owned PostgreSQL databases."""

import json
import os
import subprocess
import sys
from dataclasses import replace
from pathlib import Path
from typing import Any, cast

from conftest import PostgresFixture
from psycopg import connect
from psycopg.sql import SQL, Identifier

_DDL = """
    CREATE SCHEMA "Export Test";
    CREATE TYPE "Export Test"."State" AS ENUM ('open', 'closed');
    CREATE TABLE "Export Test"."Par.ent" (
        id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        tenant integer NOT NULL CHECK (tenant >= 1 AND tenant <= 5),
        status "Export Test"."State" NOT NULL,
        label text NOT NULL,
        note text,
        UNIQUE (tenant, id)
    );
    CREATE TABLE "Export Test".children (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tenant integer NOT NULL,
        parent_id bigint NOT NULL,
        amount numeric(12, 3) NOT NULL,
        FOREIGN KEY (tenant, parent_id) REFERENCES "Export Test"."Par.ent" (tenant, id)
    );
    CREATE TABLE "Export Test".empty (id integer);
"""
_COUNTS = """
    SELECT (SELECT count(*) FROM "Export Test"."Par.ent"),
           (SELECT count(*) FROM "Export Test".children),
           (SELECT count(*) FROM "Export Test".empty)
"""
_REFERENCE = """
    SELECT p.id, p.tenant, p.status, p.label, p.note, c.id, c.amount
    FROM "Export Test"."Par.ent" p JOIN "Export Test".children c
        ON (p.tenant, p.id) = (c.tenant, c.parent_id)
    ORDER BY c.id
"""


def _seed(
    path: Path, postgres: PostgresFixture, command: str, *options: str
) -> subprocess.CompletedProcess[str]:
    env = {key: value for key, value in os.environ.items() if not key.upper().startswith("PG")}
    env.update(SEED_TEST_URL=postgres.url, PYTHONIOENCODING="utf-8")
    binary = Path(sys.executable).with_name("seed.exe" if os.name == "nt" else "seed")
    return subprocess.run(
        [str(binary), command, "--config", str(path), "--json", *options],
        env=env,
        cwd=path.parent,
        encoding="utf-8",
        capture_output=True,
        timeout=30,
        check=False,
    )


def _payload(process: subprocess.CompletedProcess[str]) -> dict[str, Any]:
    assert process.returncode == 0, process.stderr or process.stdout
    payload: dict[str, Any] = json.loads(process.stdout)
    assert payload["version"] == 1 and payload["ok"]
    return cast(dict[str, Any], payload["data"])


def test_installed_export_round_trips_and_preserves_the_source(
    postgres: PostgresFixture, tmp_path: Path
) -> None:
    postgres.sql(_DDL)
    postgres.sql("""
        INSERT INTO "Export Test"."Par.ent" (tenant, status, label)
        VALUES (1, 'open', 'source-only');
    """)
    seq = """SELECT last_value, is_called FROM "Export Test"."Par.ent_id_seq" """
    before_sequence = postgres.sql(seq)
    config = tmp_path / "seed.toml"
    contents = """
version = 1
[database]
url_env = "SEED_TEST_URL"
schema = "Export Test"
[generation]
random_seed = 42
batch_size = 2
null_rate = 1
[tables."Par.ent"]
rows = 4
[tables.children]
rows = 7
[tables.empty]
rows = 0
[rules."Par.ent".label]
generator = "constant"
value = "é, quoted \\"text\\" and 'apostrophe'\\n\\\\q"
[rules.children.amount]
generator = "constant"
value = "123456.789"
"""
    config.write_text(contents, encoding="utf-8")
    snapshot = _payload(_seed(config, postgres, "inspect"))["schema"]
    _payload(_seed(config, postgres, "plan"))
    _payload(_seed(config, postgres, "validate"))
    _payload(_seed(config, postgres, "validate", "--dataset"))
    preview = _payload(_seed(config, postgres, "preview", "--limit", "2"))["tables"]

    manifests = {}
    for format_name in ("sql", "csv", "json"):
        path = tmp_path / format_name
        proc = _seed(config, postgres, "export", "--format", format_name, "--output", str(path))
        data = _payload(proc)["export"]
        assert data["format"] == format_name and data["manifest"] == "manifest.json"
        assert sorted(item["rows"] for item in data["counts"]) == [0, 4, 7]
        manifest = json.loads((path / data["manifest"]).read_text(encoding="utf-8"))
        manifests[format_name] = manifest
        assert postgres.env["SEED_FIXTURE_PASSWORD"] not in proc.stdout + proc.stderr
        assert "source-only" not in "".join(
            (path / file).read_text(encoding="utf-8") for file in data["artifacts"]
        )
    assert len({item["schema_fingerprint"] for item in manifests.values()}) == 1

    dataset = json.loads((tmp_path / "json" / "dataset.json").read_text(encoding="utf-8"))
    rows = {table["table"]["table"]: table for table in dataset["tables"]}
    for sample in preview:
        table = rows[sample["table"]["table"]]
        assert table["columns"] == sample["columns"]
        assert table["rows"][:2] == sample["rows"]
    parents = {(row[1], row[0]) for row in rows["Par.ent"]["rows"]}
    assert all(type(id_) is str for _, id_ in parents)
    assert all(
        (row[1], row[2]) in parents and row[3] == "123456.789" for row in rows["children"]["rows"]
    )

    config.write_text(contents.replace("batch_size = 2", "batch_size = 5"), encoding="utf-8")
    _payload(_seed(config, postgres, "export", "--format", "json"))
    repeated = tmp_path / "seed-export" / "dataset.json"
    assert repeated.read_bytes() == (tmp_path / "json" / "dataset.json").read_bytes()
    occupied = _seed(config, postgres, "export", "--format", "json")
    assert occupied.returncode == 6
    assert json.loads(occupied.stdout)["issues"][-1]["code"] == "OUTPUT_EXISTS"
    assert _payload(_seed(config, postgres, "inspect"))["schema"] == snapshot
    assert postgres.sql(_COUNTS) == "1|0|0" and postgres.sql(seq) == before_sequence

    for database in ("export_sql_import", "export_csv_import"):
        postgres.sql(f"CREATE DATABASE {database}")
    sql_target = replace(postgres, database="export_sql_import")
    csv_target = replace(postgres, database="export_csv_import")
    for target in (sql_target, csv_target):
        target.sql(_DDL)
    sql_target.script((tmp_path / "sql" / "dataset.sql").read_text(encoding="utf-8"))
    with connect(csv_target.url) as connection, connection.cursor() as cursor:
        for entry in manifests["csv"]["tables"]:
            table_name = entry["table"]
            columns = SQL(", ").join(Identifier(column["name"]) for column in entry["columns"])
            table = Identifier(table_name["schema"], table_name["table"])
            statement = SQL("COPY {} ({}) FROM STDIN WITH (FORMAT csv, HEADER true)").format(
                table, columns
            )
            with cursor.copy(statement) as copy:
                copy.write((tmp_path / "csv" / entry["file"]).read_bytes())
    assert sql_target.sql(_REFERENCE) == csv_target.sql(_REFERENCE)
    for target in (sql_target, csv_target):
        assert target.sql(_COUNTS) == "4|7|0"
        # Operator reconciles owned sequences after an explicit-ID import.
        assert target.sql(seq) == "1|f"
        assert (
            target.sql("""
            SELECT setval('"Export Test"."Par.ent_id_seq"',
                GREATEST((SELECT last_value FROM "Export Test"."Par.ent_id_seq"),
                         (SELECT max(id) FROM "Export Test"."Par.ent")), true);
        """)
            == "4"
        )
        assert (
            target.sql("""
            INSERT INTO "Export Test"."Par.ent" (tenant, status, label)
            VALUES (1, 'open', 'follow-up') RETURNING id;
        """).splitlines()[0]
            == "5"
        )


def test_export_generation_failure_leaves_no_success_marker(
    postgres: PostgresFixture, tmp_path: Path
) -> None:
    postgres.sql("""
        CREATE SCHEMA export_failed;
        CREATE TABLE export_failed.items (value boolean NOT NULL UNIQUE);
    """)
    path = tmp_path / "seed.toml"
    path.write_text(
        """
version = 1
[database]
url_env = "SEED_TEST_URL"
schema = "export_failed"
[generation]
batch_size = 1
default_rows = 2
[rules.items.value]
generator = "constant"
value = true
""",
        encoding="utf-8",
    )
    process = _seed(path, postgres, "export", "--format", "json")
    assert process.returncode == 4
    payload = json.loads(process.stdout)
    assert payload["data"] is None and not payload["ok"]
    assert not (tmp_path / "seed-export" / "manifest.json").exists()
    assert postgres.sql("SELECT count(*) FROM export_failed.items") == "0"
