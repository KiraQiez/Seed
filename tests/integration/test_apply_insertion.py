"""Live keys and all-or-nothing insertion against PostgreSQL."""

from pathlib import Path

from conftest import PostgresFixture
from test_apply_safety import config_for

from seed.apply import apply_preflight
from seed.database import open_session, parse_database_url
from seed.insertion import WriteResult, execute_apply
from seed.planning import PlanRequest


def run_apply(postgres: PostgresFixture, schema: str, tables: str) -> WriteResult:
    url = parse_database_url(postgres.url, {})
    config = config_for(postgres, schema, tables=tables)
    request = PlanRequest(Path("unused"), None, [], None, None, None)
    with open_session(url, config.database) as connection:
        approved = apply_preflight(connection, url, config, request)
        return execute_apply(connection, url, config, request, approved)


def test_live_keys_are_allocated_by_postgresql_and_used_by_children(
    postgres: PostgresFixture,
) -> None:
    postgres.sql("""
        CREATE SCHEMA live_apply_fixture;
        CREATE TABLE live_apply_fixture.parent (
            id bigint GENERATED ALWAYS AS IDENTITY (START WITH 50) PRIMARY KEY
        );
        CREATE TABLE live_apply_fixture.child (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            parent_id bigint NOT NULL REFERENCES live_apply_fixture.parent(id)
        );
    """)
    result = run_apply(
        postgres,
        "live_apply_fixture",
        "[tables.parent]\nrows=3\n[tables.child]\nrows=5",
    )
    assert result.status == 0 and result.insertion.outcome == "committed"
    assert result.insertion.counts is not None
    assert [(item.table.table, item.rows) for item in result.insertion.counts] == [
        ("parent", 3),
        ("child", 5),
    ]
    assert postgres.sql("SELECT min(id), max(id) FROM live_apply_fixture.parent") == "50|52"
    assert (
        postgres.sql("""
        SELECT count(*) FROM live_apply_fixture.child AS child
        JOIN live_apply_fixture.parent AS parent ON parent.id = child.parent_id
    """)
        == "5"
    )


def test_server_failure_in_later_batch_rolls_back_all_rows(postgres: PostgresFixture) -> None:
    postgres.sql("""
        CREATE SCHEMA rollback_apply_fixture;
        CREATE TABLE rollback_apply_fixture.parent (
            id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY
        );
        CREATE TABLE rollback_apply_fixture.child (
            id smallint GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 2) PRIMARY KEY,
            parent_id bigint NOT NULL REFERENCES rollback_apply_fixture.parent(id)
        );
    """)
    result = run_apply(
        postgres,
        "rollback_apply_fixture",
        "[tables.parent]\nrows=3\n[tables.child]\nrows=3",
    )
    assert result.status == 6 and result.insertion.outcome == "rolled_back"
    assert result.insertion.counts is None
    assert result.issue is not None and result.issue.code == "INSERT_FAILED"
    for table in ("parent", "child"):
        assert postgres.sql(f"SELECT count(*) FROM rollback_apply_fixture.{table}") == "0"
    assert postgres.sql("SELECT is_called FROM rollback_apply_fixture.parent_id_seq") == "t"
